/**
 * Retorna o SVG inline de um ícone Lucide.
 *
 * @param string $name  Nome do ícone (chave em faruk_icon_paths()).
 * @param string $class Classes Tailwind aplicadas ao <svg>.
 * @return string
 */
function faruk_icon( string $name, string $class = 'h-5 w-5' ): string {
	$paths = faruk_icon_paths();

	if ( ! isset( $paths[ $name ] ) ) {
		return '';
	}

	return sprintf(
		'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="%s" aria-hidden="true" focusable="false">%s</svg>',
		esc_attr( $class ),
		$paths[ $name ] // Markup estático definido acima, não vem de entrada do usuário.
	);
}

/**
 * Imprime o SVG inline de um ícone Lucide.
 *
 * @param string $name  Nome do ícone.
 * @param string $class Classes Tailwind aplicadas ao <svg>.
 */
function faruk_the_icon( string $name, string $class = 'h-5 w-5' ): void {
	// phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- markup estático, classes já escapadas.
	echo faruk_icon( $name, $class );
}
